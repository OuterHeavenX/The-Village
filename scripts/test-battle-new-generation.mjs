import assert from 'node:assert/strict';
import { CORE_TOWER_REGISTRY, NEW_CORE_TOWERS } from '../src/Battle/Towers/towerRegistry.js';
import { placementFeedback } from '../src/Battle/placementSystem.js';
import { battlefieldLimits } from '../src/Battle/battlefieldConfig.js';
import { draftWeightProfile } from '../src/Battle/Cards/draftWeights.js';
import { waveBreathingPeriod, waveIdentity, waveSpawnCount } from '../src/Battle/waveDirector.js';
import { authoredRoadPlans, roadSegmentsForPlan } from '../src/Battle/Environment/roadRegistry.js';

assert.deepEqual(CORE_TOWER_REGISTRY.map(t => t.id), ['dagger','axe','crossbow','ballista','holy','arcane']);
assert.equal(NEW_CORE_TOWERS.length, 3);
assert.deepEqual(battlefieldLimits(1), { stage: 1, towers:10, groundDefense:4, total:10, attack:10, supportUtility:10 });
assert.deepEqual(battlefieldLimits(10), { stage:10, towers:12, groundDefense:5, total:12, attack:12, supportUtility:12 });
assert.deepEqual(battlefieldLimits(20), { stage:20, towers:16, groundDefense:7, total:16, attack:16, supportUtility:16 });
const state = { towers: [], traps: [], path: [{x:2,y:2}], draftsCompleted: 0, chapterWaves: 8 };
assert.equal(placementFeedback(state,{type:'tower',range:2},2,3,true).valid,true);
assert.equal(placementFeedback(state,{type:'tower',range:1},8,8,true).valid,false);
assert.equal(draftWeightProfile(state).tower,.7);
state.towers=Array.from({length:10},(_,i)=>({x:i,y:1}));assert.equal(draftWeightProfile(state,battlefieldLimits(1)).tower,0);
state.towers=[];state.traps=Array.from({length:4},(_,i)=>({x:i,y:2}));assert.equal(placementFeedback(state,{type:'tower',range:2},2,3,true).valid,true,'ground defenses must not consume tower capacity');assert.equal(placementFeedback(state,{type:'trap'},2,2,true).valid,false,'ground-defense capacity must be independent');
assert.equal(waveIdentity(5,8),'miniboss');assert.equal(waveIdentity(8,8),'boss');
assert.ok(waveSpawnCount(30)<=14);assert.ok(waveBreathingPeriod(8,8)>waveBreathingPeriod(2,8));
const stage1Road=authoredRoadPlans(1),stage5Road=authoredRoadPlans(5),stage10Road=authoredRoadPlans(10),stage11Road=authoredRoadPlans(11);
assert.equal(stage1Road.plans.length,1);assert.equal(stage5Road.plans.length,2);assert.equal(stage10Road.plans.length,2);assert.equal(stage11Road.plans.length,3);
assert.ok(stage1Road.initialLength>=13,'the opening front must reach beyond the Cathedral cluster');
assert.ok(Math.min(...stage5Road.plans[0].map(cell=>cell.x))<=2,'the left breach must use the outer courtyard');
assert.ok(Math.max(...stage5Road.plans[1].map(cell=>cell.x))>=14,'the right breach must use the outer courtyard');
assert.ok(stage5Road.initialLength<stage5Road.plans[0].length,'future Stage 5 road must begin hidden');
assert.deepEqual(stage5Road.events.filter(item=>item.type==='OPEN_ROUTE').map(item=>item.wave),[5]);
assert.deepEqual(stage10Road.events.filter(item=>item.routeIndex===1).map(item=>item.wave),[4,7,9]);
assert.deepEqual(stage11Road.events.filter(item=>item.type==='OPEN_ROUTE').map(item=>item.routeIndex),[1,2]);
assert.ok(roadSegmentsForPlan(stage10Road.plans[0]).length>1,'authored routes must be segmented for staged reveals');
console.log('Battle New Generation architecture tests passed.');
